#!/usr/bin/env python3
"""Write src/lib/milestones/advancement-icons.ts from a Minecraft jar (run with python3 -I).

    python3 -I scripts/advancement-icons.py <minecraft-client-or-server.jar>

The cakeutils API names an advancement but not its picture, so the site keeps the one fact it needs from the
game's data: which item each vanilla advancement shows as its icon (data/minecraft/advancement/**.json,
display.icon.id). Only ids go into the file, no game assets: the picture itself is the item's icon from the
cakeutils catalogue. Advancements without a display (recipe unlocks) are left out. Re-run after a game update.
"""
import json
import os
import re
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PREFIX = "data/minecraft/advancement/"
ID = re.compile(r"^[a-z0-9_.-]+:[a-z0-9_./-]+$")


def main(jar):
    z = zipfile.ZipFile(jar)
    out = {}
    for name in sorted(z.namelist()):
        if not name.startswith(PREFIX) or not name.endswith(".json"):
            continue
        try:
            display = json.loads(z.read(name)).get("display")
        except ValueError:
            continue
        if not isinstance(display, dict) or not isinstance(display.get("icon"), dict):
            continue
        item = display["icon"].get("id")
        if isinstance(item, str) and ID.match(item):
            out["minecraft:" + name[len(PREFIX):-5]] = item
    if not out:
        sys.exit("no advancements with an icon in " + jar)
    version = "unknown"
    try:
        version = str(json.loads(z.read("version.json")).get("id", version))
    except (KeyError, ValueError):
        pass
    if not re.match(r"^[A-Za-z0-9 ._-]{1,40}$", version):
        version = "unknown"
    path = os.path.join(ROOT, "src", "lib", "milestones", "advancement-icons.ts")
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/advancement-icons.py from Minecraft %s: do not edit by hand.\n" % version)
        f.write("// The item each vanilla advancement shows as its icon in the game (ids only, no game assets).\n")
        f.write("export const ADVANCEMENT_ICONS: Record<string, string> = {\n")
        for k in sorted(out):
            f.write("  %s: %s,\n" % (json.dumps(k), json.dumps(out[k])))
        f.write("};\n")
    print("wrote %s (%d advancements, Minecraft %s)" % (os.path.relpath(path, ROOT), len(out), version))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
