#!/usr/bin/env python3
"""Turn GNU Unifont into the journal book's fallback glyphs (run with python3 -I; needs Pillow).

    python3 -I scripts/unifont.py <unifont.otf|ttf>

The game draws every character its bitmap fonts lack from Unifont, at half size, with the glyph trimmed to
its ink: advance = (rightmost - leftmost + 1) / 2 + 1, the leftmost ink column drawn at the pen position
(Minecraft's unihex provider). This writes, for every code point the font has:

- static/mc/unifont/<page>.png: one 256 x 256 sheet per 256 code points (page = code point >> 8, hex),
  16 x 16 cells of 16 x 16 pixels, ink black on transparent (book text is black);
- src/lib/server/onesoul/unifont-data.ts: a string with one line per page, `<page hex> <512 chars>`, two characters per code
  point: the leftmost ink column (hex) and the ink width (`0`..`g` = 0..16), `--` for a code point the font
  lacks. A blank glyph has width 0 and keeps its cell's advance (5 or 9). The server reads it and sends the
  journal page only the characters it uses.

Unifont is free software (GPL 2+ with the font embedding exception, or SIL OFL 1.1).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = "0123456789abcdefg"


def main(path):
    from fontTools.ttLib import TTFont  # only for the code point list

    cps = sorted(cp for cp in TTFont(path).getBestCmap() if cp >= 0x20 and not 0x7F <= cp < 0xA0)
    font = ImageFont.truetype(path, 16, layout_engine=ImageFont.Layout.BASIC)  # no shaping: one code point, one glyph
    out = os.path.join(ROOT, "static", "mc", "unifont")
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(out):
        if f.endswith(".png"):
            os.remove(os.path.join(out, f))
    pages = {}
    for cp in cps:
        pages.setdefault(cp >> 8, []).append(cp)
    lines = []
    for page, members in sorted(pages.items()):
        sheet = Image.new("1", (256, 256), 0)
        meta = ["--"] * 256
        for cp in members:
            cell = Image.new("1", (16, 16), 0)
            d = ImageDraw.Draw(cell)
            d.fontmode = "1"
            d.text((0, 14), chr(cp), font=font, fill=1, anchor="ls")
            box = cell.getbbox()
            i = cp & 0xFF
            if box:
                left, right = box[0], box[2] - 1
                meta[i] = f"{left:x}{W[right - left + 1]}"
                sheet.paste(cell, ((i % 16) * 16, (i // 16) * 16))
            else:
                meta[i] = "00"
        if any(m not in ("--", "00") for m in meta):
            rgba = Image.new("RGBA", (256, 256), (0, 0, 0, 0))
            rgba.paste((0, 0, 0, 255), mask=sheet)
            rgba.save(os.path.join(out, f"{page:x}.png"), optimize=True)
        lines.append(f"{page:x} {''.join(meta)}")
    with open(os.path.join(ROOT, "src", "lib", "server", "onesoul", "unifont-data.ts"), "w") as f:
        f.write("// Generated by scripts/unifont.py from GNU Unifont: per page, the leftmost ink column and ink width\n")
        f.write("// of every code point. Do not edit by hand.\n")
        f.write("export default `\n" + "\n".join(lines) + "\n`;\n")
    print(f"{len(cps)} code points, {len(pages)} pages")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
